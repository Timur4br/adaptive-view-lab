"""Export compact, traceable browser data from a completed reference run."""
import argparse, csv, hashlib, json, sys, shutil
from pathlib import Path
import numpy as np

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'research'))
import run_experiments as ref

def export(results):
    summary=json.loads((results/'summary.json').read_text(encoding='utf-8'))
    settings=json.loads((results/'settings.json').read_text(encoding='utf-8'))
    if settings['additional_actions']!=8 or settings['initial_frames']!=6:
        raise ValueError('The current web interface requires six initial frames and eight additional actions.')
    source_hash=hashlib.sha256((ROOT/'research/run_experiments.py').read_bytes()).hexdigest()
    manifest=json.loads((results/'run_manifest.json').read_text(encoding='utf-8'))
    if source_hash!=manifest['source_sha256']:
        raise ValueError('The research source does not match the source recorded for this run.')
    for name in ['summary.json','summary.csv','settings.json','checks.json','paired_comparisons.json','covariance_check.json','run_manifest.json']:
        source=results/name;target=ROOT/'data/published'/name
        if source.exists() and source.resolve()!=target.resolve():shutil.copy2(source,target)
    groups={};golden={}
    with (results/'trajectories.csv').open(encoding='utf-8-sig') as f:
        for r in csv.DictReader(f):
            key=(r['scenario'],r['strategy'],int(r['step']))
            v=groups.setdefault(key,[0.,0.,0,0.])
            v[0]+=float(r['error_mm'])**2;v[1]+=float(r['u_mm']);v[2]+=1;v[3]+=float(r['covered95'])
            if int(r['trial'])==0:
                golden.setdefault(r['scenario'],{}).setdefault(r['strategy'],[]).append({
                    'step':int(r['step']),'action':int(r['action_index']),
                    'q':float(r['q_mm']),'u':float(r['u_mm'])})
    curves=[dict(scenario=s,strategy=t,step=k,rmse=(v[0]/v[2])**.5,meanU=v[1]/v[2],coverage=v[3]/v[2])
            for (s,t,k),v in groups.items()]
    cases={}
    for name,config in ref.SCENARIOS.items():
        bank=np.load(results/f'observations_{name}.npz')
        C,R,family,labels=ref.fixture(config)
        order=[x['action'] for x in golden[name]['random'] if x['step']>0]
        cases[name]=dict(name=name,config=config,pixels=bank['pixels'][0].tolist(),
            visible=bank['visible'][0].tolist(),referenceObserved=float(bank['reference_observed_mm'][0]),
            views=[dict(center=C[i].tolist(),rotation=R[i].tolist(),family=int(family[i]),label=labels[i]) for i in range(len(C))],
            randomOrder=order+[i for i in range(6,len(C)) if i not in order])
    payload=dict(metadata=dict(date='2026-11-06',trialsPerScenario=summary[0]['n'],independentSessions=sum(x['n'] for x in summary if x['strategy']=='adaptive'),
          sourceSha256=hashlib.sha256((ROOT/'research/run_experiments.py').read_bytes()).hexdigest(),
          trajectoriesSha256=hashlib.sha256((results/'trajectories.csv').read_bytes()).hexdigest()),
        truthPoints=ref.P_TRUE.tolist(),truthLength=ref.Q_TRUE,referenceLength=ref.L_TRUE,
        summary=summary,curves=curves,cases=cases,
        paired=json.loads((results/'paired_comparisons.json').read_text()),
        covariance=json.loads((results/'covariance_check.json').read_text()))
    (ROOT/'assets/research-data.js').write_text('/* Generated by scripts/export_web_data.py. Do not edit by hand. */\nwindow.NBV_DATA = '+json.dumps(payload,separators=(',',':'),ensure_ascii=False)+';\n',encoding='utf-8')
    (ROOT/'tests/fixtures/reference-cases.json').write_text(json.dumps(dict(cases=cases,golden=golden),separators=(',',':')),encoding='utf-8')
    (ROOT/'data/published/curves.json').write_text(json.dumps(curves,indent=2),encoding='utf-8')
    print('Exported 5 session banks, 35 strategy summaries and 315 curve points')

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--results',type=Path,required=True)
    export(p.parse_args().results)
